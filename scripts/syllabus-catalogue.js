// Writes src/ai/syllabus-catalogue.js: the id, title and text of every roadmap
// module and tool card, for the Worker to embed when matching syllabus topics.
// The Worker can't import tools.js (its lazy view imports would pull every
// visualiser into the bundle), so this slim copy is generated instead.
// Run by `npm run build`; test/syllabus.test.js fails if it is stale.
//   node scripts/syllabus-catalogue.js
import { writeFile } from "node:fs/promises";
import { ROADMAPS } from "../public/js/roadmaps.js";
import { TOOLS } from "../public/js/tools.js";
import { buildCatalogue, forServer, shortHash } from "../public/js/syllabus/catalogue.js";

export const CATALOGUE_FILE = new URL("../src/ai/syllabus-catalogue.js", import.meta.url).pathname;

export function catalogueSource() {
  const entries = forServer(buildCatalogue(ROADMAPS, TOOLS));
  const version = shortHash(JSON.stringify(entries), 10);
  return `// Generated by scripts/syllabus-catalogue.js from the roadmaps and tools. Don't edit by hand.
export const CATALOGUE_VERSION = ${JSON.stringify(version)};
export const CATALOGUE = ${JSON.stringify(entries, null, 0).replace(/\},\{/g, "},\n  {")};
`;
}

export async function writeCatalogue() {
  await writeFile(CATALOGUE_FILE, catalogueSource());
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeCatalogue();
  console.log(`Wrote ${CATALOGUE_FILE}`);
}
