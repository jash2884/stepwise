// Writes src/ai/ask/tool-cards.js: one "tool card" per visualiser (title,
// subject, summary, description, keywords and example requests) for the /ask
// router's retrieval index. tools.js can't be bundled into the Worker (it
// lazy-loads every view), so the cards are generated here. `npm run build`
// runs this; a test fails if the committed file is stale.
import { writeFile } from "node:fs/promises";
import { SUBJECTS, TOOLS } from "../public/js/tools.js";
import { SCHEMA_BY_SLUG } from "../public/js/ai/tool-schemas.js";

export function buildCards() {
  return TOOLS.map((t) => {
    const s = SCHEMA_BY_SLUG.get(t.slug);
    return {
      slug: t.slug, title: t.title, subject: SUBJECTS.find((x) => x.id === t.subject)?.name ?? t.subject,
      summary: t.summary, description: t.description, keywords: s?.keywords ?? "",
      examples: (s?.examples ?? []).map((e) => e.request),
    };
  });
}

export const cardsSource = () => `// Generated by scripts/ai-cards.js from public/js/tools.js and the AI tool schemas. Do not edit.\nexport const CARDS = ${JSON.stringify(buildCards(), null, 1)};\n`;

export async function writeCards() {
  await writeFile(new URL("../src/ai/ask/tool-cards.js", import.meta.url), cardsSource());
}

if (import.meta.url === `file://${process.argv[1]}`) await writeCards();
